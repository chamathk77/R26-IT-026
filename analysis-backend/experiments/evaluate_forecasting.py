"""
Rolling-origin evaluation of the Novelty 1 forecasting ladder (thesis Chapters 3 and 6).

Run from analysis-backend/:   .venv/bin/python -m experiments.evaluate_forecasting

Datasets
  S1  seed      30 synthetic restaurant branches, 36 complete months each, generated by a
                faithful port of backend/.../seed/seedForecastData.js (order-level simulation).
  S2  shocks    Same branches with an extra month-level demand shock of +/-12 % (sensitivity).
  S3  devdb     The development branch history produced by the real JS seed and read from
                MongoDB (data/dev_branch_monthly.csv), clean complete months only.
  S4  stale     The same branch exactly as the app sees it today: the last two "complete"
                months are a half-recorded month and a month with 3 test orders.

Every origin t (training length) from 3 to N-1 is a fold; forecasts for h = 1..12 are scored
where the actual is known. Methods: the production ladder (forecast_series) and four baselines.
"""

import calendar
import csv
import json
import math
import os
import sys
from datetime import date

import numpy as np
from scipy.stats import wilcoxon

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from app.novelty01Forecasting.forecasting import (  # noqa: E402
    _holt_linear_forecast,
    forecast_series,
)

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "results")
HORIZON = 12
SEASON = 12
REPLICATES = 30
MONTHS = 36

# ---------------------------------------------------------------- generator (port of the JS seed)
BASE_ORDERS_PER_DAY = 18
MONTHLY_GROWTH_RATE = 0.006
INGREDIENT_COST_RATIO = 0.32
MONTH_SEASONALITY = [0.88, 0.9, 0.97, 1.18, 1.0, 0.92, 1.02, 1.1, 0.95, 0.98, 1.05, 1.28]
WEEKDAY_SEASONALITY_SUN_FIRST = [1.2, 0.85, 0.85, 0.9, 1.0, 1.25, 1.4]
PRICES = np.array([850, 780, 550, 600, 950, 1250, 700, 900, 1100, 1650, 1850, 1450, 2400,
                   320, 480, 250, 220, 450, 380, 520], dtype=float)
WEIGHTS = np.array([10, 8, 7, 5, 12, 7, 6, 9, 6, 5, 4, 3, 2, 11, 8, 7, 9, 6, 5, 4], dtype=float)
PROBS = WEIGHTS / WEIGHTS.sum()


def generate_branch(rng, months=MONTHS, start=date(2023, 1, 1), month_shock=0.0):
    sales, costs = [], []
    for i in range(months):
        y, m = start.year + (start.month - 1 + i) // 12, (start.month - 1 + i) % 12 + 1
        growth = (1 + MONTHLY_GROWTH_RATE) ** i
        days = calendar.monthrange(y, m)[1]
        weekday = [(date(y, m, d).weekday() + 1) % 7 for d in range(1, days + 1)]  # 0 = Sunday
        noise = rng.uniform(0.82, 1.18, days)
        orders_per_day = np.maximum(1, np.rint(
            BASE_ORDERS_PER_DAY * growth * MONTH_SEASONALITY[m - 1]
            * np.array([WEEKDAY_SEASONALITY_SUN_FIRST[w] for w in weekday]) * noise)).astype(int)
        n_orders = int(orders_per_day.sum())
        n_items = int(rng.integers(1, 5, n_orders).sum())
        products = rng.choice(len(PRICES), size=n_items, p=PROBS)
        qty = rng.integers(1, 4, n_items)
        month_sales = float((PRICES[products] * qty).sum())
        if month_shock:
            month_sales *= rng.uniform(1 - month_shock, 1 + month_shock)

        month_cost = 85000.0
        month_cost += 220000 * growth * rng.uniform(0.98, 1.03)
        month_cost += 38000 * growth * rng.uniform(0.88, 1.15)
        month_cost += month_sales * INGREDIENT_COST_RATIO
        if rng.random() < 0.55:
            month_cost += rng.uniform(12000, 45000)
        if rng.random() < 0.4:
            month_cost += rng.uniform(8000, 60000)
        sales.append(month_sales)
        costs.append(month_cost)
    return sales, costs


def load_devdb():
    rows = list(csv.DictReader(open(os.path.join(HERE, "data", "dev_branch_monthly.csv"))))
    complete = [r for r in rows if r["partial"] != "true"]
    return complete


# ---------------------------------------------------------------- baselines
def naive(train, h):
    return [train[-1]] * h


def seasonal_naive(train, h):
    if len(train) < SEASON:
        return None
    return [train[len(train) - SEASON + (k % SEASON)] for k in range(h)]


def moving_average_3(train, h):
    return [float(np.mean(train[-3:]))] * h


def linear_trend(train, h):
    x = np.arange(len(train))
    slope, intercept = np.polyfit(x, train, 1)
    return [max(0.0, intercept + slope * (len(train) - 1 + k)) for k in range(1, h + 1)]


def holt_only(train, h):
    """Ablation: the ladder without its seasonal rung (damped Holt from 4 points)."""
    if len(train) < 4:
        return moving_average_3(train, h)
    return [max(0.0, v) for v in _holt_linear_forecast(train, h)["forecast"]]


def revised_ladder(train, h):
    """Experimental variant suggested by the band results: MA(3) < 12, seasonal naive 12-23, production >= 24."""
    if len(train) < 12:
        return moving_average_3(train, h)
    if len(train) < 24:
        return seasonal_naive(train, h)
    return [p["predicted"] for p in forecast_series(train, h, SEASON)["points"]]


BASELINES = {
    "naive": naive,
    "seasonal_naive": seasonal_naive,
    "moving_average_3": moving_average_3,
    "linear_trend": linear_trend,
    "holt_no_season": holt_only,
    "revised_ladder": revised_ladder,
}


def mase_scale(train):
    """In-sample one-step MAE of the seasonal naive (m=12) or, for short series, the naive."""
    train = np.asarray(train, dtype=float)
    lag = SEASON if len(train) > SEASON else 1
    diffs = np.abs(train[lag:] - train[:-lag])
    scale = float(diffs.mean()) if len(diffs) else float("nan")
    return scale if scale > 0 else float("nan")


# ---------------------------------------------------------------- evaluation
def evaluate_series(scenario, series_id, target, values, rows, min_origin=3):
    n = len(values)
    for t in range(min_origin, n):
        train = values[:t]
        h_max = min(HORIZON, n - t)
        actual = values[t:t + h_max]
        scale = mase_scale(train)

        ladder = forecast_series(train, HORIZON, SEASON)
        for k in range(h_max):
            p = ladder["points"][k]
            rows.append([scenario, series_id, target, "ladder", ladder["method"], t, k + 1,
                         actual[k], p["predicted"], p["lower"], p["upper"], scale])
        for name, fn in BASELINES.items():
            fc = fn(train, h_max)
            if fc is None:
                continue
            for k in range(h_max):
                rows.append([scenario, series_id, target, name, name, t, k + 1,
                             actual[k], fc[k], "", "", scale])


def history_band(t):
    if t < 6:
        return "3-5"
    if t < 12:
        return "6-11"
    if t < 18:
        return "12-17"
    if t < 24:
        return "18-23"
    return "24-35"


def summarise(rows):
    """Aggregate per scenario/target/method/horizon and per history band."""
    def agg(sel):
        a = np.array([r[7] for r in sel], dtype=float)
        p = np.array([r[8] for r in sel], dtype=float)
        s = np.array([r[11] for r in sel], dtype=float)
        e = a - p
        nz = a != 0
        ok = np.isfinite(s)
        return {
            "n": len(sel),
            "mape": float(np.mean(np.abs(e[nz] / a[nz])) * 100) if nz.any() else None,
            "mae": float(np.mean(np.abs(e))),
            "rmse": float(np.sqrt(np.mean(e ** 2))),
            "mase": float(np.mean(np.abs(e[ok]) / s[ok])) if ok.any() else None,
        }

    out = {"by_horizon_common": [], "by_history": [], "coverage": [], "models_used": [], "wilcoxon": []}
    groups = {}
    for r in rows:
        groups.setdefault((r[0], r[2], r[3]), []).append(r)

    # Same folds for every method: origins with at least 12 months, where the seasonal naive exists.
    for (scen, target, method), base in sorted(groups.items()):
        for h in (1, 3, 6, 12):
            sel = [r for r in base if r[6] == h and r[5] >= SEASON]
            if sel:
                out["by_horizon_common"].append({"scenario": scen, "target": target, "method": method, "h": h, **agg(sel)})
        for band in ("3-5", "6-11", "12-17", "18-23", "24-35"):
            sel = [r for r in base if history_band(r[5]) == band and r[6] <= 3]
            if sel:
                out["by_history"].append({"scenario": scen, "target": target, "method": method,
                                          "history": band, "h_max": 3, **agg(sel)})

    for scen, target in sorted({(k[0], k[1]) for k in groups}):
        lad = groups[(scen, target, "ladder")]
        for part, cond in (("all", lambda t: True), ("lt24", lambda t: t < 24), ("ge24", lambda t: t >= 24)):
            for h in (1, 3, 6, 12):
                sel = [r for r in lad if r[6] == h and cond(r[5])]
                if not sel:
                    continue
                inside = [r[9] <= r[7] <= r[10] for r in sel]
                width = [(r[10] - r[9]) / r[7] * 100 for r in sel if r[7]]
                out["coverage"].append({"scenario": scen, "target": target, "folds": part, "h": h, "n": len(sel),
                                        "coverage": float(np.mean(inside) * 100),
                                        "mean_width_pct_of_actual": float(np.mean(width))})
        for model in sorted({r[4] for r in lad}):
            out["models_used"].append({"scenario": scen, "target": target, "model": model,
                                       "folds": len({(r[1], r[5]) for r in lad if r[4] == model})})

        # Paired Wilcoxon signed-rank tests on absolute errors, per history band.
        for other, band, lo, hi in (("seasonal_naive", "12-23", 12, 24), ("seasonal_naive", "24-35", 24, 99),
                                    ("moving_average_3", "3-11", 3, 12)):
            for h in (1, 3):
                pairs = {}
                for method in ("ladder", other):
                    for r in groups.get((scen, target, method), []):
                        if r[6] == h and lo <= r[5] < hi:
                            pairs.setdefault((r[1], r[5]), {})[method] = abs(r[7] - r[8])
                a = [v["ladder"] for v in pairs.values() if len(v) == 2]
                b = [v[other] for v in pairs.values() if len(v) == 2]
                if len(a) >= 10:
                    stat = wilcoxon(a, b)
                    out["wilcoxon"].append({"scenario": scen, "target": target, "against": other, "history": band,
                                            "h": h, "pairs": len(a),
                                            "median_abs_err_ladder": float(np.median(a)),
                                            "median_abs_err_other": float(np.median(b)),
                                            "ladder_better_share": float(np.mean(np.array(a) < np.array(b)) * 100),
                                            "p_value": float(stat.pvalue)})
    return out


def horizon_totals(rows):
    """Error of the 3- and 12-month totals shown on the app's cards, on common folds (origin >= 12)."""
    out = []
    folds = {}
    for r in rows:
        if r[5] >= SEASON:
            folds.setdefault((r[0], r[2], r[3], r[1], r[5]), []).append(r)
    for scen, target in sorted({(k[0], k[1]) for k in folds}):
        for method in ("ladder", "seasonal_naive", "revised_ladder", "moving_average_3"):
            for span in (3, 12):
                errs = []
                for key, fold in folds.items():
                    if key[0] == scen and key[1] == target and key[2] == method:
                        part = [r for r in fold if r[6] <= span]
                        if len(part) == span:
                            a = sum(r[7] for r in part)
                            errs.append(abs(a - sum(r[8] for r in part)) / a * 100)
                if errs:
                    out.append({"scenario": scen, "target": target, "method": method, "months": span,
                                "folds": len(errs), "mape_of_total": float(np.mean(errs))})
    return out


def stale_case(dev):
    """Reproduce what the app shows for the dev branch, and the forecast if the gap is trimmed."""
    months = [r["month"] for r in dev]
    sales = [float(r["sales"]) for r in dev]
    costs = [float(r["costs"]) for r in dev]
    as_is_s, as_is_c = forecast_series(sales, 13), forecast_series(costs, 13)
    clean_n = months.index("2026-08")  # last fully recorded month is 2026-07
    trim_s, trim_c = forecast_series(sales[:clean_n], 13), forecast_series(costs[:clean_n], 13)
    return {
        "history_months_as_is": len(sales),
        "last_months_as_is": dict(zip(months[-3:], sales[-3:])),
        "as_is": {"method": as_is_s["method"], "sales_next3": [p["predicted"] for p in as_is_s["points"][:3]],
                  "costs_next3": [p["predicted"] for p in as_is_c["points"][:3]],
                  "sales_backtest_mape": as_is_s["backtest"]["mape"] if as_is_s["backtest"] else None,
                  "costs_backtest_mape": as_is_c["backtest"]["mape"] if as_is_c["backtest"] else None},
        "trimmed_to": months[clean_n - 1],
        "trimmed": {"method": trim_s["method"], "sales_next3": [p["predicted"] for p in trim_s["points"][:3]],
                    "costs_next3": [p["predicted"] for p in trim_c["points"][:3]],
                    "sales_backtest_mape": trim_s["backtest"]["mape"] if trim_s["backtest"] else None,
                    "costs_backtest_mape": trim_c["backtest"]["mape"] if trim_c["backtest"] else None,
                    "params": trim_s["params"]},
    }


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for scenario, shock in (("S1_seed", 0.0), ("S2_shocks", 0.12)):
        for rep in range(REPLICATES):
            rng = np.random.default_rng(1000 + rep)  # same branches in S1 and S2, plus the shock
            start = date(2023, 1 + rep % 12, 1)
            s, c = generate_branch(rng, start=start, month_shock=shock)
            evaluate_series(scenario, rep, "sales", s, rows)
            evaluate_series(scenario, rep, "costs", c, rows)
        print(scenario, "done", len(rows), flush=True)

    dev = load_devdb()
    clean = dev[: [r["month"] for r in dev].index("2026-08")]
    evaluate_series("S3_devdb", 0, "sales", [float(r["sales"]) for r in clean], rows)
    evaluate_series("S3_devdb", 0, "costs", [float(r["costs"]) for r in clean], rows)

    with open(os.path.join(OUT, "fold_forecasts.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["scenario", "series", "target", "method", "model", "train_months", "h",
                    "actual", "predicted", "lower", "upper", "mase_scale"])
        w.writerows(rows)

    summary = summarise(rows)
    summary["horizon_totals"] = horizon_totals(rows)
    summary["stale_case"] = stale_case(dev)
    summary["config"] = {"replicates": REPLICATES, "months": MONTHS, "horizon": HORIZON,
                         "season": SEASON, "seeds": "numpy default_rng(1000 + replicate)",
                         "shock_S2": 0.12}
    with open(os.path.join(OUT, "summary.json"), "w") as f:
        json.dump(summary, f, indent=2)
    print("rows", len(rows), "->", OUT)


if __name__ == "__main__":
    main()
